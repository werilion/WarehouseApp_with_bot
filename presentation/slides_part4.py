# ---------------- 26. этапы ----------------

def s27_stages(c, num):
    page_bg(c)
    top = header(c, "04 / Результат", "Этапы разработки",
                 "От анализа аналогов до документации. На каждом этапе — проверяемый результат.")

    stages = [
        ("01", "Анализ", ["4 класса аналогов", "боли пользователей", "требования к MVP"], "таблица аналогов", BLUE),
        ("02", "Проектирование", ["ER-модель данных", "семантическая модель", "сценарии пользователя"], "3 схемы", ORANGE),
        ("03", "Ядро учёта", ["вход и 3 роли", "товары и контрагенты", "приход, расход, транзакции"], "рабочий контур", BLUE),
        ("04", "Аналитика", ["инвентаризация", "история операций", "отчёты и CSV"], "2 отчёта", GREEN),
        ("05", "Помощь", ["126 узлов бота", "обращения и статусы", "пользователи, настройки"], "бот + тикеты", ORANGE),
        ("06", "Оформление", ["README и SQL-скрипт", "модель и схемы", "презентация проекта"], "документация", NAVY),
    ]
    w, h = 280, 146
    for i, (n, title, items, artifact, color) in enumerate(stages):
        x = M + (i % 3) * (w + 16)
        y = 264 - (i // 3) * (h + 16)
        card(c, x, y, w, h, fill=WHITE, stroke=BORDER)
        c.setFillColor(color)
        c.rect(x, y + h - 4, w, 4, fill=1, stroke=0)
        text(c, x + 16, y + h - 26, n, FONT_B, 8.0, color)
        text(c, x + 38, y + h - 27, title, FONT_B, 12.2, TEXT)
        yy = y + h - 48
        for it in items:
            c.setFillColor(color)
            c.circle(x + 20, yy + 2, 1.6, fill=1, stroke=0)
            text(c, x + 28, yy, it, FONT, 8.2, MUTED)
            yy -= 19
        rounded(c, x + 16, y + 14, sw(artifact, FONT_B, 6.8) + 16, 16, r=8,
                fill=HexColor("#F3F6FA"), stroke=None)
        text(c, x + 24, y + 20, artifact, FONT_B, 6.8, color)

    text(c, M, 66, "Каждый этап заканчивался артефактом: схемой, экраном или документом.",
         FONT, 8.6, MUTED)


