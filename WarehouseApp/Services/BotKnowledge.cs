        /// <summary>Разбирает строку вида «слово=вес,слово=вес» в список ключевых слов.</summary>
        private static (string Word, int Weight)[] K(string s)
        {
            return s.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
                    .Select(x => { var p = x.Split('='); return (p[0], int.Parse(p[1])); })
                    .ToArray();
        }

        private static Dictionary<string, BotNode> ParseTree(string text)
        {
            var nodes = new Dictionary<string, BotNode>();
            foreach (var line in text.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            {
                var p = line.Split('|');
                var node = new BotNode { Id = p[1], IsQuestion = p[0] == "q", Text = p[2] };
                if (node.IsQuestion)
                {
                    for (int i = 3; i < p.Length; i++)
                    {
                        var option = p[i].Split('>');
                        node.Options.Add((option[0], option[1]));
                    }
                }
                else if (p.Length > 3)
                {
                    node.Options.Add(("", p[3]));
                }
                nodes[node.Id] = node;
            }
            return nodes;
        }

