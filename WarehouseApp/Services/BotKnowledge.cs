    /// <summary>Узел дерева диалога: вопрос с вариантами ответа или действие.</summary>
    public class BotNode
    {
        public string Id { get; set; } = "";
        public bool IsQuestion { get; set; }
        public string Text { get; set; } = "";
        /// <summary>Для вопроса: варианты ответа (подпись, id следующего узла). Для действия: один переход без подписи.</summary>
        public List<(string Label, string Target)> Options { get; } = new();
    }

    /// <summary>Тема обращения: по ключевым словам бот входит в нужное место дерева.</summary>
    public record BotIntent(string Entry, string Intro, (string Word, int Weight)[] Keywords);

